import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const checks = [];
const read = (p) => fs.readFileSync(path.join(root,p),'utf8');
const assert = (name, condition) => { checks.push({name,pass:Boolean(condition)}); };
const migration = read('apps/api/src/db/242_p541_security_reliability.sql');
const app = read('apps/api/src/app.ts');
const limiter = read('apps/api/src/middleware/securityRateLimit.ts');
const route = read('apps/api/src/routes/securityAudit.ts');
const integration = read('apps/api/src/routes/enterpriseIntegrations.ts');
assert('append-only audit event table', /CREATE TABLE IF NOT EXISTS security_audit_events/.test(migration));
assert('audit mutation rejection trigger', /BEFORE UPDATE OR DELETE ON security_audit_events/.test(migration));
assert('recovery evidence schema', /operational_recovery_evidence/.test(migration));
assert('audit read is authenticated and tenant-scoped', /authenticate, requireOrgScope/.test(route));
assert('audit read permission enforced', /security:audit:read/.test(route));
assert('audit query filters organisation', /WHERE organisation_id=\$1/.test(route));
assert('auth endpoints rate limited', /app\.use\(securityRateLimit\)/.test(app));
assert('rate limit returns 429', /status\(429\)/.test(limiter));
assert('rate limit only targets credential mutation endpoints', /auth\\\/\(login\|refresh\|forgot-password\|reset-password/.test(limiter));
assert('integration create/configure/revoke audit evidence', ['INTEGRATION_CREATED','INTEGRATION_CONFIGURED','INTEGRATION_REVOKED'].every(x=>integration.includes(x)));
assert('rate limit multi-instance limitation documented', /Multi-instance deployments MUST/.test(limiter));
assert('version synchronized', read('VERSION').trim()==='0.541.0-dev' && read('apps/api/src/config/version.ts').includes('0.541.0-dev'));
const failed=checks.filter(x=>!x.pass);
for(const c of checks) console.log(`${c.pass?'PASS':'FAIL'} ${c.name}`);
console.log(`P541 SECURITY CHECKS: ${checks.length-failed.length}/${checks.length} PASS`);
if(failed.length) process.exit(1);
