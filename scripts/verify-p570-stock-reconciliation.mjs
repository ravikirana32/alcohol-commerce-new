import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const checks=[];
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const migration=read('apps/api/src/db/246_p570_stock_reconciliation.sql');
const route=read('apps/api/src/routes/operations.ts');
const service=read('apps/api/src/services/stockReconciliation.ts');
const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
add('migration creates reconciliation run table',/CREATE TABLE IF NOT EXISTS stock_reconciliation_runs/.test(migration));
add('migration creates scoped exception table',/CREATE TABLE IF NOT EXISTS stock_reconciliation_exceptions/.test(migration)&&/organisation_id,outlet_id,status/.test(migration));
add('service scopes all ledger and balance reads by organisation and outlet',/sm\.organisation_id=p\.organisation_id AND sm\.outlet_id=\$2/.test(service)&&/b\.organisation_id=p\.organisation_id AND b\.outlet_id=\$2/.test(service));
add('known inbound movement types classified',/RECEIPT','TRANSFER_IN','RETURN/.test(service));
add('known outbound movement types classified',/SALE','TRANSFER_OUT','WASTAGE','SUPPLIER_RETURN/.test(service));
add('adjustment movements explicitly excluded and surfaced',/movement_type='ADJUSTMENT'/.test(service)&&/UNCLASSIFIED_ADJUSTMENT/.test(route));
add('reconciliation endpoint is permission protected',/post\('\/inventory\/reconciliation-runs',requirePermission\('inventory:read'\)/.test(route));
add('exception list and controlled status workflow exist',/get\('\/inventory\/reconciliation-exceptions'/.test(route)&&/post\('\/inventory\/reconciliation-exceptions\/:exceptionId\/status',requirePermission\('inventory:adjust'\)/.test(route));
add('reconciliation does not auto-correct stock balances',!/UPDATE stock_balances|INSERT INTO stock_balances/.test(route.slice(route.indexOf("// P570:"),route.indexOf('// P574: maker-checker variance correction requests'))));
add('run and exception records are organisation scoped',/WHERE id=\$4 AND organisation_id=\$5/.test(route)&&/WHERE organisation_id=\$1/.test(route));
for(const c of checks) console.log(`${c.ok?'PASS':'FAIL'} ${c.name}`);
console.log(`${checks.filter(c=>c.ok).length}/${checks.length} passed`);
if(checks.some(c=>!c.ok))process.exit(1);
