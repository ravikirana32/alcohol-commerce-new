import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
const root = process.cwd();
const checks = [];
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
function check(name, fn) { try { if (!fn()) throw new Error('condition returned false'); checks.push({name,ok:true}); } catch (e) { checks.push({name,ok:false,error:e.message}); } }
const auth = read('apps/api/src/middleware/authenticate.ts');
const login = read('apps/api/src/routes/auth.ts');
const seed = read('apps/api/src/db/seed-demo-users.ts');
const guard = read('apps/api/src/middleware/requirePermission.ts');
const scope = read('apps/api/src/services/permissionScope.ts');
const permissionTest = read('apps/api/src/middleware/requirePermission.test.ts');
const scopeTest = read('apps/api/src/services/permissionScope.test.ts');
check('Authentication reloads active membership on each request', () => /status = 'ACTIVE'/.test(auth) && /MEMBERSHIP_REVOKED/.test(auth));
check('Authentication loads grants from role_permissions', () => /FROM role_permissions/.test(auth));
check('Login requires active organisation membership for tenant users', () => /NO_ORGANISATION_ACCESS/.test(login) && /status = 'ACTIVE'/.test(login));
check('Permission middleware denies missing grants', () => /permissions\.includes\(permission\)/.test(guard) && /PERMISSION_DENIED/.test(guard));
check('Demo seeder creates memberships for non-platform roles', () => /organisation_memberships/.test(seed) && /user_outlet_access/.test(seed));
check('Demo seeder blocks production and requires explicit opt-in', () => /nodeEnv === 'production'/.test(seed) && /DEMO_SEED_ENABLED/.test(seed));
check('Outlet permission helper enforces exact outlet scope', () => /g\.outletId===undefined\|\|g\.outletId===outletId/.test(scope));
check('Middleware tests cover 401, allow, deny and exact-match behavior', () => ['401','403','similar permission','exact permission'].every(s => permissionTest.includes(s)));
check('Outlet scope tests cover match, mismatch and org-wide grant', () => ['outlet-a','outlet-b','inventory:read','finance:manage'].every(s => scopeTest.includes(s)));
check('P546 runbook documents dynamic demo role accounts', () => /DEMO_SEED_PASSWORD/.test(read('P546-RUNBOOK.md')) && /demo\.acp\.local/.test(read('P546-RUNBOOK.md')));
check('Tenant authorization is explicitly recorded as runtime-pending', () => /tenant isolation/i.test(read('P513-P546-Cumulative-Gap-Register.md')));
const failed = checks.filter(c=>!c.ok);
for (const c of checks) console.log(`${c.ok?'PASS':'FAIL'} ${c.name}${c.error?`: ${c.error}`:''}`);
console.log(`P547 RBAC static checks: ${checks.length-failed.length}/${checks.length} PASS`);
if (failed.length) process.exit(1);
