import fs from 'node:fs';
import path from 'node:path';
const root = process.cwd();
const checks = [];
const add = (name, ok, detail='') => checks.push({name, ok, detail});
const seed = fs.readFileSync(path.join(root,'apps/api/src/db/seed-demo-users.ts'),'utf8');
const auth = fs.readFileSync(path.join(root,'apps/api/src/routes/auth.ts'),'utf8');
const schema = fs.readFileSync(path.join(root,'apps/api/src/db/002_auth_tenancy.sql'),'utf8');
const pkg = JSON.parse(fs.readFileSync(path.join(root,'apps/api/package.json'),'utf8'));
add('Seeder refuses production environment', seed.includes("nodeEnv === 'production'"));
add('Seeder requires explicit opt-in', seed.includes("DEMO_SEED_ENABLED === 'true'"));
add('Seeder requires operator-supplied strong password', seed.includes('password.length < 14'));
add('Passwords hashed with bcrypt cost 12', seed.includes('bcrypt.hash(password, 12)'));
add('Roles discovered from role_permissions table', seed.includes('SELECT DISTINCT role_code FROM role_permissions'));
add('Platform administrator account is special-cased', seed.includes("roleCode === 'PLATFORM_ADMIN'"));
add('Non-platform users receive organisation membership', seed.includes('INSERT INTO organisation_memberships'));
add('Non-platform users receive outlet access', seed.includes('INSERT INTO user_outlet_access'));
add('Seeder uses transaction and rollback', seed.includes('BEGIN') && seed.includes('ROLLBACK') && seed.includes('COMMIT'));
add('Seeder does not print passwords or password hashes', !/console\.log\([^\n]*(password|hash)/i.test(seed));
add('Auth login supports seeded email/password and organisation selection', auth.includes("authRouter.post('/login'") && auth.includes('bcrypt.compare'));
add('Role and membership schema exists', schema.includes('CREATE TABLE IF NOT EXISTS organisation_memberships') && schema.includes('CREATE TABLE IF NOT EXISTS role_permissions'));
add('npm seed command is wired', pkg.scripts?.['db:seed:demo'] === 'tsx src/db/seed-demo-users.ts');
const failed = checks.filter(c=>!c.ok);
for (const c of checks) console.log(`${c.ok?'PASS':'FAIL'} ${c.name}${c.detail?`: ${c.detail}`:''}`);
console.log(`P546 static checks: ${checks.length-failed.length}/${checks.length} PASS`);
if (failed.length) process.exit(1);
