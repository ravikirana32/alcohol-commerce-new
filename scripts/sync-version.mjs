import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const versionFile = path.join(root, 'VERSION');
const version = fs.readFileSync(versionFile, 'utf8').trim();
if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(version)) {
  throw new Error(`Invalid VERSION value: ${version}`);
}
for (const file of ['package.json', 'apps/api/package.json', 'apps/web/package.json']) {
  const fullPath = path.join(root, file);
  const pkg = JSON.parse(fs.readFileSync(fullPath, 'utf8'));
  pkg.version = version;
  fs.writeFileSync(fullPath, `${JSON.stringify(pkg, null, 2)}\n`);
}
fs.writeFileSync(path.join(root, 'apps/api/src/config/version.ts'), `// Generated by scripts/sync-version.mjs. Do not edit manually.\nexport const APP_VERSION = '${version}';\n`);
fs.writeFileSync(path.join(root, 'apps/web/src/config/version.ts'), `// Generated by scripts/sync-version.mjs. Do not edit manually.\nexport const APP_VERSION = '${version}';\n`);
console.log(`Synchronized application version ${version}`);
